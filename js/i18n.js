function applyLanguage(lang) {
  document.documentElement.setAttribute("lang", lang === "es" ? "es" : "en");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = STRINGS[lang] && STRINGS[lang][key];
    if (value) el.textContent = value;
  });
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.classList.toggle("is-active", btn.getAttribute("data-lang-btn") === lang);
  });
  const waMsg = STRINGS[lang]["whatsapp.msg"];
  document.querySelectorAll("[data-whatsapp]").forEach((a) => {
    const phone = a.getAttribute("data-whatsapp");
    a.setAttribute("href", `https://wa.me/${phone}?text=${encodeURIComponent(waMsg)}`);
  });
  try {
    localStorage.setItem("althaya-lang", lang);
  } catch (e) {}
}

function initLanguage() {
  let lang = "en";
  try {
    lang = localStorage.getItem("althaya-lang") || "en";
  } catch (e) {}
  applyLanguage(lang);
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.getAttribute("data-lang-btn")));
  });
}

document.addEventListener("DOMContentLoaded", initLanguage);
